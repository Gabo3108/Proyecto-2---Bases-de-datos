CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    grupo_edad VARCHAR(15) NOT NULL CHECK (grupo_edad IN ('adulto','niño','mayor','estudiante'))
);
CREATE TABLE taquillero (
    id_taquillero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);
CREATE TABLE operador (
    id_operador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);
CREATE TABLE contador (
    id_contador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);
CREATE TABLE administrador (
    id_admin BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL
);

-- 2. Cartelera, salas y asientos
CREATE TABLE pelicula (
    id_pelicula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    sinopsis TEXT NOT NULL,
    clasificacion VARCHAR(20) NOT NULL,
    duracion_min INT NOT NULL CHECK (duracion_min > 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE sala (
    id_sala BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    ubicacion VARCHAR(200) NOT NULL,
    capacidad INT NOT NULL CHECK (capacidad > 0)
);
CREATE TABLE asiento (
    id_sala BIGINT NOT NULL REFERENCES sala(id_sala),
    numero VARCHAR(12) NOT NULL,
    zona VARCHAR(30) NOT NULL DEFAULT 'general',
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id_sala, numero)
);
CREATE TABLE funcion (
    id_funcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pelicula BIGINT NOT NULL REFERENCES pelicula(id_pelicula),
    id_sala BIGINT NOT NULL REFERENCES sala(id_sala),
    fecha_hora TIMESTAMPTZ NOT NULL,
    precio_base NUMERIC(12,2) NOT NULL CHECK (precio_base >= 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    id_admin_creador BIGINT REFERENCES administrador(id_admin),
    UNIQUE (id_funcion, id_sala)
);

-- 3. Compra, pago 
CREATE TABLE compra (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    id_taquillero BIGINT REFERENCES taquillero(id_taquillero), 
    creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    estado VARCHAR(15) NOT NULL DEFAULT 'pendiente'
      CHECK (estado IN ('pendiente','pagada','fallida','cancelada','reembolsada'))
);
CREATE TABLE pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT NOT NULL REFERENCES compra(id_compra),
    referencia_externa VARCHAR(120) UNIQUE,
    metodo VARCHAR(30) NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto >= 0),
	estado VARCHAR(15) NOT NULL
      CHECK (estado IN ('pendiente','aprobado','rechazado','reembolsado')),
    procesado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE entrada (
	id_entrada INT PRIMARY KEY,
	funciOn VARCHAR(40),
	asiento INT,
	CONSTRAINT fk_asiento
	FOREIGN KEY (asiento) REFERENCES asiento(numero),
	dia TIMESTAMP,
	hora TIME,
	tarifa DECIMAL,
	id_taquillero INT,
	CONSTRAINT fk_taquillero
	FOREIGN KEY (id_taquillero) REFERENCES taquillero(id_taquillero), 
	id_funcion INT,
	CONSTRAINT fk_funcion
	FOREIGN KEY (id_funcion) REFERENCES funcion(id_funcion), 
	id_sala INT, 
	CONSTRAINT fk_sala
	FOREIGN KEY (id_sala) REFERENCES sala(id_sala)
);
CREATE UNIQUE INDEX ux_entrada_funcion_asiento_vigente
  ON entrada (id_funcion, id_sala, numero_asiento)
  WHERE estado IN ('emitida','usada');
CREATE TABLE comprobante (
    id_qr BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entrada BIGINT NOT NULL UNIQUE REFERENCES entrada(id_entrada),
    codigo_qr UUID NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Bloqueo temporal de un asiento por funcion (liberacion al vencer plazo)
CREATE TABLE bloqueo_asiento (
    id_bloqueo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
    id_funcion BIGINT NOT NULL,
    id_sala BIGINT NOT NULL,
    numero_asiento VARCHAR(12) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	vence_en TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '2 minutes'),
    estado VARCHAR(12) NOT NULL DEFAULT 'activo'
      CHECK (estado IN ('activo','liberado','comprado','expirado')),
    CHECK (vence_en > creado_en),
    FOREIGN KEY (id_funcion, id_sala) REFERENCES funcion(id_funcion, id_sala),
    FOREIGN KEY (id_sala, numero_asiento) REFERENCES asiento(id_sala, numero)
);
CREATE UNIQUE INDEX ux_bloqueo_activo_por_asiento
  ON bloqueo_asiento (id_funcion, id_sala, numero_asiento)
  WHERE estado = 'activo';

-- 5. Auditorias separadas, segun el enunciado
CREATE TABLE transaccion_log (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT REFERENCES compra(id_compra),
    id_pago BIGINT REFERENCES pago(id_pago),
    tipo_evento VARCHAR(60) NOT NULL,
    detalle JSONB,
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE asiento_auditoria_log (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcion BIGINT REFERENCES funcion(id_funcion),
    id_sala BIGINT REFERENCES sala(id_sala),
    numero_asiento VARCHAR(12),
    id_cliente BIGINT REFERENCES cliente(id_cliente),
    tipo_evento VARCHAR(40) NOT NULL,
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE acceso_puerta_log (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entrada BIGINT REFERENCES entrada(id_entrada),
    id_operador BIGINT REFERENCES operador(id_operador),
    dispositivo VARCHAR(80) NOT NULL,
    resultado VARCHAR(20) NOT NULL CHECK (resultado IN ('exitoso','rechazado')),
    motivo VARCHAR(120),
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE admin_operacion_audit (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin BIGINT NOT NULL REFERENCES administrador(id_admin),
    rol VARCHAR(40) NOT NULL DEFAULT 'administrador',
    direccion_ip INET,
    operacion VARCHAR(80) NOT NULL,
    tabla_afectada VARCHAR(80) NOT NULL,
    registro_id BIGINT,
    detalle JSONB,
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Indices 
CREATE INDEX ix_funcion_cartelera ON funcion (fecha_hora, id_sala) WHERE activa;
